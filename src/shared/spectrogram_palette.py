"""Spectrogram colour palettes and call-band colouring, shared by the live
microphone monitor and the controller's post-processing renders
(plans/spectrogram-palettes-and-call-bands.md).

A palette is a list of colour stops ``[(pos 0-1, "#rrggbb"), ...]``, turned
into a 256-entry lookup table. The built-ins live in
``spectrogram_palettes.json`` next to this file (generated by
``tools/gen_spectrogram_palettes.py``; the frontend imports the same file).

Call bands colour a frequency range with its own palette -- e.g. rat alarm
calls (18-32 kHz) blue, appetitive calls (45-96 kHz) orange. The colour mode
picks one palette for the whole image ("palette") or the bands ("bands"), in
which case rows outside every band are drawn grey, so only the bands are in
colour. This is colouring by **frequency**, not call detection: anything in
the band, noise included, gets the band's colour.

numpy only; images are BGR (both consumers are OpenCV).
"""

from __future__ import annotations

import functools
import itertools
import json
import os
import re
from dataclasses import dataclass

import numpy as np

_JSON_PATH = os.path.join(os.path.dirname(__file__), "spectrogram_palettes.json")
_HEX = re.compile(r"#[0-9a-fA-F]{6}")
MAX_BANDS = 4
MAX_STOPS = 64


class PaletteError(ValueError):
    pass


@functools.lru_cache(maxsize=1)
def _doc() -> dict:
    with open(_JSON_PATH) as f:
        return json.load(f)


def builtin_palettes() -> dict[str, list[list]]:
    """name -> stops, for every built-in palette (old aliased names included,
    so a saved setting that uses one keeps working)."""
    stops = {p["name"]: p["stops"] for p in _doc()["palettes"]}
    for old, new in _doc().get("aliases", {}).items():
        stops.setdefault(old, stops[new])
    return stops


def default_palette() -> str:
    return _doc()["default"]


def band_presets() -> list[dict]:
    return [dict(p) for p in _doc()["band_presets"]]


def validate_stops(stops) -> tuple[tuple[float, str], ...]:
    """Normalise and check a stop list; raises PaletteError. Positions must
    start at 0, end at 1 and strictly increase."""
    if not isinstance(stops, (list, tuple)) or not 2 <= len(stops) <= MAX_STOPS:
        raise PaletteError(f"a palette needs 2-{MAX_STOPS} colour stops")
    out = []
    for s in stops:
        if not isinstance(s, (list, tuple)) or len(s) != 2:
            raise PaletteError("each stop must be [position, '#rrggbb']")
        pos, colour = s
        try:
            pos = float(pos)
        except (TypeError, ValueError) as exc:
            raise PaletteError(f"bad stop position {pos!r}") from exc
        if not isinstance(colour, str) or not _HEX.fullmatch(colour):
            raise PaletteError(f"bad stop colour {colour!r} (want #rrggbb)")
        out.append((pos, colour.lower()))
    positions = [p for p, _ in out]
    if positions[0] != 0.0 or positions[-1] != 1.0:
        raise PaletteError("stop positions must start at 0 and end at 1")
    if any(b <= a for a, b in itertools.pairwise(positions)):
        raise PaletteError("stop positions must strictly increase")
    return tuple(out)


@functools.lru_cache(maxsize=64)
def _lut_cached(stops: tuple[tuple[float, str], ...]) -> np.ndarray:
    pos = np.array([p for p, _ in stops]) * 255.0
    rgb = np.array([[int(c[i:i + 2], 16) for i in (1, 3, 5)] for _, c in stops],
                   dtype=float)
    x = np.arange(256)
    lut = np.stack([np.interp(x, pos, rgb[:, ch]) for ch in (2, 1, 0)], axis=1)
    lut = np.round(lut).astype(np.uint8)
    lut.setflags(write=False)
    return lut


def lut(stops) -> np.ndarray:
    """(256, 3) uint8 BGR lookup table for a stop list (read-only, cached)."""
    return _lut_cached(validate_stops(stops))


def resolve_stops(name: str | None, stops=None) -> tuple[tuple[float, str], ...]:
    """Stops for a palette setting: explicit `stops` win (a custom palette
    resolved by the controller), else the built-in `name`, else the
    default. Never raises: a bad setting falls back to the default."""
    if stops:
        try:
            return validate_stops(stops)
        except PaletteError:
            pass
    builtins = builtin_palettes()
    key = str(name or "").lower()
    return validate_stops(builtins.get(key) or builtins[default_palette()])


@dataclass(frozen=True)
class CallBand:
    lo_hz: float
    hi_hz: float
    stops: tuple[tuple[float, str], ...]
    label: str = ""

    @classmethod
    def from_dict(cls, d: dict) -> CallBand:
        try:
            lo, hi = float(d["lo_hz"]), float(d["hi_hz"])
        except (KeyError, TypeError, ValueError) as exc:
            raise PaletteError("a call band needs numeric lo_hz and hi_hz") from exc
        if not 0 <= lo < hi:
            raise PaletteError(f"call band {lo:g}-{hi:g} Hz: lo must be below hi")
        if d.get("stops"):
            stops = validate_stops(d["stops"])
        else:
            name = str(d.get("palette") or "")
            if name.lower() not in builtin_palettes():
                raise PaletteError(f"unknown palette {name!r}")
            stops = resolve_stops(name)
        return cls(lo, hi, stops, str(d.get("label") or ""))


def parse_bands(raw) -> list[CallBand]:
    """Enabled call bands from a config list, sorted by frequency. Raises
    PaletteError on a malformed entry, overlap, or too many bands."""
    if not raw:
        return []
    if not isinstance(raw, list):
        raise PaletteError("call bands must be a list")
    bands = [CallBand.from_dict(d) for d in raw
             if isinstance(d, dict) and d.get("enabled", True)]
    if len(bands) > MAX_BANDS:
        raise PaletteError(f"at most {MAX_BANDS} call bands")
    bands.sort(key=lambda b: b.lo_hz)
    for a, b in itertools.pairwise(bands):
        if b.lo_hz < a.hi_hz:
            raise PaletteError(
                f"call bands {a.lo_hz:g}-{a.hi_hz:g} and {b.lo_hz:g}-{b.hi_hz:g} Hz overlap")
    return bands


COLOUR_MODES = ("palette", "bands")


def resolve_colouring(mode, palette_name, stops, raw_bands
                      ) -> tuple[tuple, list[CallBand], str | None]:
    """(base stops, bands, problem) for a spectrogram's colour settings.

    `mode` "palette": the whole image in the palette; saved bands are kept
    in config but not drawn. "bands": each band in its own palette, grey
    everywhere else (all grey with no bands on). Unset or unknown: bands if
    any are on, else the palette (the behaviour before the mode existed).
    `problem` is why the bands couldn't be used, if they couldn't; this
    never raises, so a bad setting can't blank a spectrogram."""
    mode = mode if mode in COLOUR_MODES else None
    base = resolve_stops(palette_name, stops)
    if mode == "palette":
        return base, [], None
    try:
        bands, problem = parse_bands(raw_bands), None
    except PaletteError as exc:
        bands, problem = [], str(exc)
    if mode is None:
        mode = "bands" if bands else "palette"
    if mode == "bands":
        return validate_stops(builtin_palettes()["grayscale"]), bands, problem
    return base, [], problem


def linear_row_hz(height: int, lo_hz: float, hi_hz: float) -> np.ndarray:
    """Frequency at each row's centre for a linear axis, top row = `hi_hz`."""
    step = (hi_hz - lo_hz) / height
    return hi_hz - (np.arange(height) + 0.5) * step


def row_luts(base_stops, bands: list[CallBand], row_hz: np.ndarray) -> np.ndarray:
    """(H, 256, 3) per-row LUT. No bands -> every row uses the base palette;
    with bands -> band rows use their band's palette, the rest greyscale."""
    h = len(row_hz)
    if not bands:
        return np.broadcast_to(lut(base_stops), (h, 256, 3))
    out = np.empty((h, 256, 3), dtype=np.uint8)
    out[:] = lut(builtin_palettes()["grayscale"])
    for b in bands:
        rows = (row_hz >= b.lo_hz) & (row_hz < b.hi_hz)
        out[rows] = lut(b.stops)
    return out


def colourise(grey: np.ndarray, base_stops, bands: list[CallBand],
              row_hz: np.ndarray) -> np.ndarray:
    """Colour an (H, W) uint8 magnitude image -> (H, W, 3) uint8 BGR."""
    if grey.ndim != 2 or grey.shape[0] != len(row_hz):
        raise ValueError("grey must be (H, W) with one row_hz entry per row")
    if not bands:
        return lut(base_stops)[grey]
    luts = row_luts(base_stops, bands, row_hz)
    return luts[np.arange(grey.shape[0])[:, None], grey]


def band_key_colour(band: CallBand) -> tuple[int, int, int]:
    """A representative bright BGR colour for drawing a band's key/label."""
    c = lut(band.stops)[200]
    return int(c[0]), int(c[1]), int(c[2])
