#!/usr/bin/env python3
"""Generate ``src/shared/spectrogram_palettes.json``: the built-in SAVIOUR
spectrogram palettes and the call-band presets.

That JSON is the single source for both sides: the Python renderers load it
through ``src/shared/spectrogram_palette.py`` and the frontend imports it for
its pickers and gradient swatches. Output is committed, so this only needs
re-running when a built-in palette or preset changes.

The perceptual and classic palettes are sampled from OpenCV's own colour-map
LUTs (the live monitor used ``cv2.applyColorMap`` with these before, so the
look doesn't change). Each is reduced to the fewest stops that rebuild the
256-entry LUT by linear interpolation to within ``MAX_ERR`` per channel.

    python3 tools/gen_spectrogram_palettes.py
"""

from __future__ import annotations

import json
import os

import cv2
import numpy as np

MAX_ERR = 2.0  # 0-255 units, per channel

# name -> (label, OpenCV colour map)
SAMPLED: dict[str, tuple[str, int]] = {
    "inferno": ("Inferno", cv2.COLORMAP_INFERNO),
    "magma": ("Magma", cv2.COLORMAP_MAGMA),
    "plasma": ("Plasma", cv2.COLORMAP_PLASMA),
    "viridis": ("Viridis", cv2.COLORMAP_VIRIDIS),
    "cividis": ("Cividis", cv2.COLORMAP_CIVIDIS),
    "turbo": ("Turbo", cv2.COLORMAP_TURBO),
    "jet": ("Jet", cv2.COLORMAP_JET),
    "hot": ("Hot", cv2.COLORMAP_HOT),
    "bone": ("Bone", cv2.COLORMAP_BONE),
    "ocean": ("Ocean", cv2.COLORMAP_OCEAN),
}

# Hand-defined palettes: name -> (label, stops)
DEFINED: dict[str, tuple[str, list[tuple[float, str]]]] = {
    "grayscale": ("Greyscale", [(0.0, "#000000"), (1.0, "#ffffff")]),
    # Call-band ramps: blue against orange stays distinct for red/green
    # colour-blind viewers. Both start at black so silence looks the same
    # inside and outside a band.
    "alarm_blue": ("Alarm blue",
                   [(0.0, "#000000"), (0.55, "#2b6cff"), (1.0, "#cfe0ff")]),
    "appetitive_orange": ("Appetitive orange",
                          [(0.0, "#000000"), (0.55, "#ff8a00"), (1.0, "#fff0c0")]),
}

BAND_PRESETS = [
    {"id": "rat_alarm", "label": "Alarm (22 kHz)",
     "lo_hz": 18000, "hi_hz": 32000, "palette": "alarm_blue"},
    {"id": "rat_appetitive", "label": "Appetitive (50 kHz)",
     "lo_hz": 45000, "hi_hz": 96000, "palette": "appetitive_orange"},
]

ORDER = ["inferno", "magma", "plasma", "viridis", "cividis", "turbo",
         "grayscale", "jet", "hot", "bone", "ocean",
         "alarm_blue", "appetitive_orange"]


def _reduce(lut: np.ndarray) -> list[int]:
    """Fewest indices whose linear interpolation rebuilds `lut` (256x3)."""
    x = np.arange(256)
    keep = [0, 255]
    while True:
        rec = np.stack([np.interp(x, keep, lut[keep, c]) for c in range(3)], 1)
        err = np.abs(rec - lut).max(axis=1)
        worst = int(err.argmax())
        if err[worst] <= MAX_ERR:
            return keep
        keep = sorted({*keep, worst})


def _hex(rgb) -> str:
    return "#" + "".join(f"{int(round(v)):02x}" for v in rgb)


def main() -> None:
    grey = np.arange(256, dtype=np.uint8).reshape(-1, 1)
    palettes = {}
    for name, (label, cmap) in SAMPLED.items():
        lut = cv2.applyColorMap(grey, cmap)[:, 0, ::-1].astype(float)  # BGR->RGB
        stops = [[round(i / 255, 4), _hex(lut[i])] for i in _reduce(lut)]
        palettes[name] = {"name": name, "label": label, "stops": stops}
    for name, (label, stops) in DEFINED.items():
        palettes[name] = {"name": name, "label": label,
                          "stops": [[p, c] for p, c in stops]}
    doc = {
        "_note": "Generated by tools/gen_spectrogram_palettes.py -- edit that, "
                 "not this file.",
        "version": 1,
        "default": "inferno",
        "palettes": [palettes[n] for n in ORDER],
        "band_presets": BAND_PRESETS,
    }
    out = os.path.join(os.path.dirname(__file__), "..", "src", "shared",
                       "spectrogram_palettes.json")
    with open(out, "w") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    print(f"wrote {os.path.normpath(out)}: "
          + ", ".join(f"{p['name']}({len(p['stops'])})" for p in doc["palettes"]))


if __name__ == "__main__":
    main()
